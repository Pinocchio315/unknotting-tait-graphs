#!/usr/bin/env python
"""Correction terms of the double branched cover from Greene's spanning-tree model (arXiv:0805.1381).

For a connected diagram D with a marked point p on the strand `mark`, the Heegaard Floer complex of Sigma_2(K) is
generated by the Kauffman states x of D (matchings crossing -> corner of an unmarked region).  Greene's Theorem 4.1
gives the absolute grading
        gr(x) = delta(x) + (q(v_x) - 2m - 3 sigma(G_W)) / 4,
where G_W is the reduced Goeritz matrix of the white graph (g_ij = sum mu over the crossings joining w_i, w_j,
g_ii = - sum mu over the crossings at w_i), m its rank, q(v) = v^T G_W^{-1} v, delta(x) the number of crossings
with mu = -1 among those where x picks a white corner, and v_x the degree vector of the orientation of the white
graph in which the edge of a crossing c points to the white region on the same side of the overstrand as x(c).
The Spin^c structure of x is the class [v_x] in coker(G_W) (Section 4.5; det odd).  The incidence number mu(c)
is +1 when the black regions sit in the corners (a,b),(c,d) of the crossing [a,b,c,d] (Figure 2: over-strand
from bottom left to top right, shaded regions left and right) and -1 otherwise.

Theorem 6.8: the E_1 page is generated by the solitary states, those x for which the union of the matching
m_x (crossing -> x(c)) and m'_x (crossing -> the other region on the same side of the overstrand as x(c)) in
the incidence graph of regions and crossings has no cycle.  When every Spin^c class contains exactly one solitary
state, Sigma_2(K) is an L-space (Corollary 6.9) and d(Sigma_2(K), t) = gr(x_t).

    python greene_dinv.py 12n_491            # correction terms, both colourings and several marked strands
    python greene_dinv.py 3_1 4_1 5_2 8_20 9_44 5_1 7_4 9_43  # small controls
"""
