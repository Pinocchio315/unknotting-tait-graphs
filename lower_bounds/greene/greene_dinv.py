def run(name, pd, marks=(1, 2, 3), verbose=True):
    results = {}
    for black in (0, 1):
        for mark in marks:
            try:
                d, multi, lam, info = correction_terms(pd, black, mark, verbose)
            except AssertionError as e:
                print('   black', black, 'mark', mark, 'failed:', e); continue
            results[(black, mark)] = (d, multi, lam, info)
            if multi: print(f'      classes with != 1 solitary state: {len(multi)} e.g. {list(multi.items())[:3]}')
    return results


